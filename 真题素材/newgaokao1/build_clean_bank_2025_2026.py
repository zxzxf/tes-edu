TYPE_NAME = {"single":"单选题","multi":"多选题","fill":"填空题","solve":"解答题"}

def dump(year, data):
    base = f"{year}全国1_含河南_题干答案_干净"
    json_path = os.path.join(HERE, base + ".json")
    md_path = os.path.join(HERE, base + ".md")
    json.dump(data, open(json_path, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    lines = [f"# {year} 新高考I卷（全国1卷）数学（含河南）题干+答案+解析 校对稿\n",
             "> 题源：本地官方 PDF（标准 LaTeX 字体抽取，公式完整，已修正抽取残字）+ 21cnjy 精品解析 + 多源官方 PDF 交叉核验",
             "> 知识点为章节级粗标，细粒度标签需待 P0 知识点 DAG（≥300 点）锁词表后回填\n"]
    for r in data:
        lines.append(f"## 第 {r['no']} 题（{TYPE_NAME[r['type']]}）\n")
        lines.append("**题干：**\n\n" + r["stem"] + "\n")
        if r["options"]:
            lines.append("\n**选项：**\n" + "\n".join(r["options"]) + "\n")
        lines.append(f"\n**答案：** {r['answer']}\n")
        lines.append(f"\n**解析：** {r['analysis']}\n")
        lines.append(f"\n**知识点 / 难度：** {r['knowledge_point']}（难度 {r['difficulty']}/5）\n")
    open(md_path, "w", encoding="utf-8").write("\n".join(lines))
    return json_path, md_path

