def build():
    nodes, idx = [], {}
    book_i = 0
    for book, chapters in BOOKS.items():
        book_i += 1
        for c_i, (chapter, sections) in enumerate(chapters, 1):
            sec_flat = []
            for s_i, (section, points) in enumerate(sections, 1):
                for k_i, name in enumerate(points, 1):
                    node_id = f"MA-B{book_i}-C{c_i}-S{s_i}-K{k_i:02d}"
                    node = {
                        "id": node_id,
                        "name": name,
                        "book": book,
                        "chapter": chapter,
                        "section": section,
                        "level": "knowledge_point",
                        "prerequisites": [],
                        "importance": "core" if any(k in name for k in CORE_KEYWORDS) else "std",
                    }
                    nodes.append(node)
                    idx[node_id] = node
                    sec_flat.append(node_id)
            # 1) 同章内串行前置
            for i in range(1, len(sec_flat)):
                nodes_by_id = {n["id"]: n for n in nodes}
                nodes_by_id[sec_flat[i]]["prerequisites"].append(sec_flat[i - 1])
            # 2) 章级跨章依赖：本章首个知识点依赖前置章的末个知识点
            for pre_ch in CHAPTER_PREREQ.get(chapter, []):
                pre_ids = [n["id"] for n in nodes if n["chapter"] == pre_ch]
                if pre_ids and sec_flat:
                    target = sec_flat[0]
                    for n in nodes:
                        if n["id"] == target and pre_ids[-1] not in n["prerequisites"]:
                            n["prerequisites"].append(pre_ids[-1])
    return nodes


def main():
    nodes = build()
    # 父子（章节层级）索引
    chapters = {}
    for n in nodes:
        chapters.setdefault(n["chapter"], {"book": n["book"], "count": 0, "sections": []})
        chapters[n["chapter"]]["count"] += 1
        if n["section"] not in chapters[n["chapter"]]["sections"]:
            chapters[n["chapter"]]["sections"].append(n["section"])

    out = {
        "meta": {
            "subject": "数学",
            "stage": "高中",
            "province": "河南",
            "textbook": "人教A版（2019版）",
            "exam": "新高考I卷",
            "version": "0.1-草案",
            "total_knowledge_points": len(nodes),
            "total_chapters": len(chapters),
            "note": "草案：术语与粒度需教研对照教材目录终校；前置边为最小可用骨架（同章串行 + 跨章关键依赖）",
        },
        "chapters": chapters,
        "nodes": nodes,
    }
    jp = os.path.join(BASE, "knowledge_dag_高中数学_人教A版_草案.json")
    json.dump(out, open(jp, "w", encoding="utf-8"), ensure_ascii=False, indent=2)

    # 教研校对稿
    mp = os.path.join(BASE, "knowledge_dag_高中数学_人教A版_草案.md")
    with open(mp, "w", encoding="utf-8") as f:
        f.write("# 高中数学知识点本体 DAG（草案 · 人教A版）\n\n")
        f.write(f"共 **{len(nodes)} 个知识点**，{len(chapters)} 章。"
                f"前置边 = 同章串行 + 跨章关键依赖。\n\n")
        f.write("> 草案，需教研对照教材目录终校术语与粒度。\n\n")
        cur_book = None
        for n in nodes:
            if n["book"] != cur_book:
                cur_book = n["book"]
                f.write(f"\n## {cur_book}\n\n")
            if n["id"].endswith("K01") and n["section"].endswith("概念") or n["id"].endswith("-S1-K01"):
                f.write(f"\n### {n['chapter']}\n\n")
            pre = "、".join(n["prerequisites"]) or "—"
            f.write(f"- `{n['id']}` **{n['name']}** ｜ {n['section']} ｜ 前置：{pre}\n")
    print(f"知识点 {len(nodes)} 个，章 {len(chapters)} 个")


if __name__ == "__main__":
    main()
