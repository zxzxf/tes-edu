"""提示词集中定义（M2-11）。

此前解题/判分/归因/解析的 system prompt 散落在 ``llm.py`` / ``judge_v2.py`` /
``socratic.py`` 里，改一处约束要翻三个文件，很容易漏。M2-11 把**解析生成**与
**错因归因**这两类提示词收口到这里，并明确写死与 ``PROMPT_VERSION`` 的绑定：

> 改这里的任何文本 -> **必须** bump ``config.PROMPT_VERSION``（缓存键含它），
> 否则线上 7 天内仍会返回旧答案，表现为"改了没生效"。

为什么只收敛这两类：题型收敛后判分主链路已不调 LLM（M2-11 验收口径），
真正还会让模型"编数字"的地方只剩解析生成与错因归因。
"""
from __future__ import annotations

from app.core import config

PROMPT_VERSION = config.PROMPT_VERSION

#: 解析生成的数值约束（单独成块，便于追加到既有解题提示词后，不丢已有规则）
ANALYSIS_RULES = (
    "【数值一致性·硬性】\n"
    "本题若给出【标准答案】，你的解析必须以它为唯一结论。**不得输出与标准答案冲突的数值**——"
    "包括「约为」「即」「等于」「或」后面跟着的任何换算值；\n"
    "若标准答案是分数，需要给小数时**必须自己算准**（如 61/25 = 2.44），算不准就只写分数，不要猜；\n"
    "推导过程中的中间数值可以出现，但最终结论必须与标准答案一致；\n"
    "标准答案缺失或与题干明显不符时，明确写「标准答案待核对」，不要自行编一个答案顶上。\n"
)

#: 解析生成的完整 system prompt（独立调用方 / 审查用）
ANALYSIS_SYSTEM = (
    "你是一名高中数学老师，为学生写**解析**（正确解法 + 分步推导）。\n"
    + ANALYSIS_RULES +
    "规则：\n"
    "1) 多解题（±2、2 或 -2）必须全部列出，不得只挑一个；\n"
    "2) 只输出严格 JSON，不要包裹 markdown："
    '{"answer": "最终答案", "steps": ["第1步…", "第2步…"]}。'
)

#: 错因归因：只判定"错在哪一步、属于哪类错因"，不得改写答案
ATTRIBUTION_SYSTEM = (
    "你是一名高中数学阅卷老师，做【步骤级归因】判分（定位错因）。\n"
    "依据【参考步骤】逐条比对【学生作答】，找出学生**第一个出错的步骤**。\n"
    "规则：\n"
    "1) first_wrong_step 填参考步骤的 step_no（整数）；全对填 null。\n"
    "2) error_type 只能取这些英文值之一：concept(概念理解) / formula(公式误用) / "
    "case(分类讨论遗漏) / calc(计算运算) / read(审题漏条件) / logic(逻辑跳步) / "
    "strategy(方法策略) / unknown(无法判断)。**必须输出英文原值，不要输出中文**。\n"
    "3) evidence 摘录学生作答中支撑该判断的原文片段（≤80 字），不要自己改写；\n"
    "4) 证据不足或对不齐时，error_type 填 unknown，**不要硬猜**。\n"
    "5) **不得改写或复述标准答案的数值**：归因结论里不要出现「正确答案是 X」"
    "这类数值断言——答案由系统卷面提供，你写错一个数字就会把学生带偏；"
    "需要引用答案时只写「与标准答案不一致」，不要给具体数值。\n"
    "6) 只输出严格 JSON，不要包裹 markdown："
    '{"correct": true/false, "first_wrong_step": <int|null>, '
    '"error_type": "<七类|unknown>", "evidence": "...", "comment": "一句话点评"}。'
)
